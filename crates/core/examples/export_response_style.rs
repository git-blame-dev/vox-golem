use std::fmt::Write;
use voxgolem_core::response_style::PLAIN_TEXT_POLICY;

// Kotlin interpolates dollars and, unlike JSON, has no form-feed escape.
fn kotlin_string(value: &str) -> String {
    let mut literal = String::from("\"");
    for ch in value.chars() {
        match ch {
            '"' => literal.push_str("\\\""),
            '\\' => literal.push_str("\\\\"),
            '$' => literal.push_str("\\$"),
            '\n' => literal.push_str("\\n"),
            '\r' => literal.push_str("\\r"),
            '\t' => literal.push_str("\\t"),
            ch if ch.is_control() => write!(literal, "\\u{:04x}", u32::from(ch)).unwrap(),
            ch => literal.push(ch),
        }
    }
    literal.push('"');
    literal
}

fn main() {
    println!(
        "// Generated by scripts/generate-model-catalog.py; edit crates/core/src/response_style.rs.\n\
         package dev.gitblame.voxgolem.assistant.runtime\n\n\
         internal object AssistantResponseStyle {{\n    const val PLAIN_TEXT_POLICY = {}\n}}",
        kotlin_string(PLAIN_TEXT_POLICY)
    );
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn kotlin_literal_escapes_interpolation_quotes_backslashes_and_controls() {
        assert_eq!(
            kotlin_string("Synthetic $name ${value} \"quoted\" \\ path\n\r\t\u{0008}\u{000c}"),
            r#""Synthetic \$name \${value} \"quoted\" \\ path\n\r\t\u0008\u000c""#
        );
    }
}

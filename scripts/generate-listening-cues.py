"""Generate listening cues exclusively from sine waves; see listening-cues.md."""
import argparse
import io
import math
from pathlib import Path
import struct
import subprocess
import tempfile
import wave

ROOT = Path(__file__).resolve().parents[1]
DESKTOP = Path("apps/desktop-tauri/src-tauri/resources")
BROWSER = Path("frontend/app/public/resources")


def wav_bytes(kind, sample_rate=48000, channels=1, frames=15360):
    """Two softly gated notes, scaled to fit the requested historical duration."""
    if kind not in ("start", "stop") or sample_rate <= 0 or channels not in (1, 2) or frames < 2:
        raise ValueError("Invalid cue format")
    frequencies = (392, 523.25) if kind == "start" else (523.25, 392)
    amplitude = 9000 if kind == "start" else 8050
    pcm = bytearray()
    for i in range(frames):
        # Normalize time to the canonical 320 ms, retaining the original pitches.
        position = i / (frames - 1)
        note = min(int(position * 2), 1)
        local = position * 2 - note
        envelope = min(1.0, local / 0.075, (1.0 - local) / 0.375)
        sample = round(amplitude * envelope * math.sin(2 * math.pi * frequencies[note] * i / sample_rate))
        pcm.extend(struct.pack("<h", sample) * channels)
    output = io.BytesIO()
    with wave.open(output, "wb") as target:
        target.setnchannels(channels)
        target.setsampwidth(2)
        target.setframerate(sample_rate)
        target.writeframes(pcm)
    return output.getvalue()


def mp3_bytes(wav):
    """Encode without source metadata; fixed ffmpeg/libmp3lame versions reproduce bytes."""
    with tempfile.TemporaryDirectory(prefix="listening-cue-") as directory:
        target = Path(directory) / "cue.mp3"
        subprocess.run(
            ["ffmpeg", "-v", "error", "-nostdin", "-f", "wav", "-i", "pipe:0",
             "-map_metadata", "-1", "-c:a", "libmp3lame", "-b:a", "128k",
             "-flags:a", "+bitexact", "-fflags", "+bitexact", "-id3v2_version", "0",
             "-write_id3v1", "0", str(target)],
            input=wav, check=True, capture_output=True,
        )
        return target.read_bytes()


def canonical_assets():
    start, stop = wav_bytes("start"), wav_bytes("stop")
    return {
        DESKTOP / "start-listening.wav": start,
        DESKTOP / "stop-listening.wav": stop,
        DESKTOP / "stop-listening.mp3": mp3_bytes(stop),
        BROWSER / "start-listening.wav": start,
        BROWSER / "stop-listening.wav": stop,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, default=ROOT)
    parser.add_argument("--check", action="store_true", help="Compare generated bytes without writing")
    args = parser.parse_args()
    mismatches = []
    for relative, data in canonical_assets().items():
        path = args.output_root / relative
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                mismatches.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if mismatches:
        parser.exit(1, "Cue assets differ from synthesis source: " + ", ".join(mismatches) + "\n")


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""Generate static Rust metadata and response policy; --check never writes sources."""
import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
HEADER = "// Generated by scripts/generate-model-catalog.py; edit crates/core/src/model_catalog.rs.\n"


def kotlin_quote(value):
    """Quote static Kotlin literals, including interpolation metacharacters."""
    if not isinstance(value, str):
        return json.dumps(value)
    return '"' + ''.join(
        "\\$" if char == "$" else "\\u000c" if char == "\f" else json.dumps(char)[1:-1]
        for char in value
    ) + '"'


def outputs():
    data = json.loads(subprocess.check_output(
        ["cargo", "run", "--quiet", "--locked", "-p", "voxgolem-core", "--no-default-features",
         "--example", "export_model_catalog"], cwd=ROOT, text=True))
    models = data["models"]
    frontend = [{k: v for k, v in model.items() if not k.startswith("android") and k != "nativeLabel"} for model in models]
    ts = HEADER + "import type { ModelCatalogEntry } from './modelCatalog'\n\n"
    ts += "export const MODEL_CATALOG = " + json.dumps(frontend, indent=2) + " as const satisfies readonly ModelCatalogEntry[]\n"
    ts += "export const DEFAULT_MODEL_CHOICES = " + json.dumps(data["defaults"], indent=2) + " as const\n"
    kotlin = HEADER + "package dev.gitblame.voxgolem.assistant.runtime\n\n"
    kotlin += """/** Static presentation only; never provider readiness or admission. */
data class AssistantModelPresentation(
    val id: String,
    val fullLabel: String,
    val familyId: String,
    val familyLabel: String,
    val compactFamilyLabel: String,
    val effort: String,
    val effortLabel: String,
    val supportsFast: Boolean = false,
)

"""
    kotlin += "/** Static labels/membership only; readiness remains owned by native providers. */\ninternal object AssistantModelCatalog {\n"
    quote = kotlin_quote
    kotlin += "    val presentation: Map<String, AssistantModelPresentation> = mapOf(\n"
    fields = ("id", "label", "familyId", "familyLabel", "androidCompactFamilyLabel", "effort", "androidEffortLabel", "supportsFast")
    kotlin += ",\n".join(
        f'        {quote(m["id"])} to AssistantModelPresentation(' +
        ', '.join(quote(m[field]) for field in fields) + ')' for m in models)
    kotlin += "\n    )\n"
    for group in ["custom", "optional"]:
        entries = [m for m in models if m["androidGroup"] == group]
        kotlin += f"    val {group}Labels = mapOf(\n"
        kotlin += ",\n".join(f'        {quote(m["id"])} to {quote(m["androidLabel"] or m["label"])}' for m in entries)
        kotlin += "\n    )\n"
    aliases = [m for m in models if m["androidGroup"] is not None]
    kotlin += '    val aliases = (customLabels.keys + optionalLabels.keys).toList()\n'
    kotlin += '    val nonAgentAliases = setOf(' + ', '.join(quote(m['id']) for m in aliases if not m['agent']) + ')\n'
    kotlin += '    val agentAliases: Set<String> = aliases.filterNot { it in nonAgentAliases }.toSet()\n}\n'
    policy = "// Generated by scripts/generate-model-catalog.py; edit crates/core/src/response_style.rs.\n"
    policy += "package dev.gitblame.voxgolem.assistant.runtime\n\n"
    policy += "internal object AssistantResponsePolicy {\n"
    policy += "    const val PLAIN_TEXT_POLICY = " + quote(data["responsePolicy"]["plainTextPolicy"]) + "\n}\n"
    return {
        ROOT / "frontend/app/src/lib/modelCatalog.generated.ts": ts,
        ROOT / "crates/assistant-android/src/main/java/dev/gitblame/voxgolem/assistant/runtime/AssistantModelCatalog.kt": kotlin,
        ROOT / "crates/assistant-android/src/main/java/dev/gitblame/voxgolem/assistant/runtime/AssistantResponsePolicy.kt": policy,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for path, text in outputs().items():
        if not path.exists() or path.read_text() != text:
            if args.check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(text)
    if stale:
        print("Stale generated static metadata/policy: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
